export function languageForPath(path: string): string {
  const ext = path.split(".").pop()?.toLowerCase() ?? "";
  const map: Record<string, string> = {
    kt: "kotlin",
    kts: "kotlin",
    java: "java",
    js: "javascript",
    mjs: "javascript",
    cjs: "javascript",
    ts: "typescript",
    tsx: "typescript",
    jsx: "javascript",
    json: "json",
    html: "html",
    css: "css",
    md: "markdown",
    xml: "xml",
    py: "python",
    gradle: "kotlin",
    properties: "properties",
    toml: "toml",
    sh: "bash",
  };
  return map[ext] ?? "plaintext";
}


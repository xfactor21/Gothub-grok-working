export function foldersFor(files: Record<string, ProjectFile>): string[] {
  const set = new Set<string>();
  for (const path of Object.keys(files)) {
    const parts = path.split("/");
    let acc = "";
    for (let i = 0; i < parts.length - 1; i++) {
      acc = acc ? `${acc}/${parts[i]}` : parts[i];
      set.add(acc);
    }
  }
  return [...set].sort();
}

export function filesForTemplate(
  id: TemplateId,
  name: string,
): Record<string, ProjectFile> {
  switch (id) {
    case "android-compose":
      return androidFiles(name);
    case "kotlin-jvm":
      return kotlinJvmFiles(name);
    case "java":
      return javaFiles(name);
    case "web-app":
      return webFiles(name);
    case "node-script":
      return nodeFiles(name);
    case "python":
      return pythonFiles(name);
    default:
      return {
        "README.md": {
          language: "markdown",
          content: `# ${name}\n\nEmpty xIDE v9 workspace.\n`,
        },
      };
  }
}
